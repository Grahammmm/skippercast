def test_original_prefetch_boxes_contained_not_equal():
    def literal(name, variable):
        for node in ast.parse((ROOT / name).read_text()).body:
            if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == variable for t in node.targets):
                return node.value
        raise AssertionError(variable)
    segments = ast.literal_eval(literal('src/skippercast/coastal/prefetch.py', 'SEGMENTS'))
    bounds_expr = literal('research/scripts/build_coast_prefetch_plan.py', 'BOUNDS')
    bounds = dict(zip(segments, ast.literal_eval(bounds_expr.args[0].args[1]), strict=True))
    mapping = {'morro-bay': ['C1'], 'cambria-san-simeon': ['C2'],
               'south-big-sur-san-simeon': ['C4'], 'santa-cruz-monterey-bay': ['C7a', 'C7b']}
    for slug, hints in mapping.items():
        w, s, e, n = load(slug)['bbox']
        for hint in hints:
            a, b, c, d = bounds[hint]
            assert w <= a < c <= e
            assert s <= b < d <= n
    santa = load('santa-cruz-monterey-bay')['bbox']
    sectors = recipe.read_json(ROOT / 'catalog/coastal-sectors.json')['sectors']
    assert santa[3] == next(r for r in sectors if r['id'] == 'pigeon-monterey')['latitude'][1]
    assert santa != bounds['C7b']
    assert santa[3] != bounds['C7b'][3]  # Do not round 37.18333333333333 to 37.183.


