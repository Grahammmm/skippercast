def test_relational_gate_mutation_control_isolated(tmp_path):
    document = load()
    document['bbox'][0] = math.nextafter(document['bbox'][0], math.inf)
    # The shape checker accepts the plausible box: only exact metadata binding
    # decides this regression. Bypass the relation solely in an inert test double
    # and demonstrate the same negative would escape without that actual gate.
    recipe._shape(document, ROOT)
    original = recipe.read_json
    def disabled_region_binding(path):
        data = original(path)
        if Path(path) == ROOT / 'regions/morro-bay/region.json':
            data = deepcopy(data)
            data['bounds'] = document['bbox']
        return data
    with pytest.raises(recipe.RecipeError, match='bbox differs'):
        validate(document, tmp_path)
    with patch.object(recipe, 'read_json', side_effect=disabled_region_binding):
        assert validate(document, tmp_path)['valid']
    assert validate(load(), tmp_path)['valid']
