def input_bytes(paths):
    total = 0
    for recipe_path, meta in ((paths[0], paths[2]), (paths[1], paths[3])):
        total += recipe_path.stat().st_size
        total += sum((meta / name).stat().st_size for name in READ_SET)
    return total


@pytest.mark.parametrize('cap', ['per-file', 'aggregate', 'rows', 'output'])
def test_a3_size_row_and_output_caps(cap, tmp_path, workspace, monkeypatch, capsys):
    paths = pair(tmp_path)
    limit = min(delta.MAX_FILE_BYTES, recipe.MAX_JSON_BYTES)
    assert delta.MAX_FILE_BYTES == 2 * 1024 * 1024 and delta.MAX_TOTAL_BYTES == 16 * 1024 * 1024
    assert delta.MAX_ROWS == 4096 and delta.MAX_OUTPUT_BYTES == 8 * 1024 * 1024
    if cap == 'per-file':
        text = paths[1].read_text().rstrip('\n')
        paths[1].write_text(text + ' ' * (limit - len(text.encode())))
        assert paths[1].stat().st_size == limit
        assert compare(paths, workspace)['change_count'] == 5        # exactly at the cap: accepted
        paths[1].write_text(text + ' ' * (limit - len(text.encode()) + 1))
        reason = 'per-file input cap'
    elif cap == 'aggregate':
        total = input_bytes(paths)
        monkeypatch.setattr(delta, 'MAX_TOTAL_BYTES', total)
        assert compare(paths, workspace)['change_count'] == 5        # exactly at the cap: accepted
        monkeypatch.setattr(delta, 'MAX_TOTAL_BYTES', total - 1)
        reason = 'aggregate input cap'
    elif cap == 'rows':
        monkeypatch.setattr(delta, 'MAX_ROWS', 5)
        assert compare(paths, workspace)['change_count'] == 5
        monkeypatch.setattr(delta, 'MAX_ROWS', 4)
        reason = 'row cap'
    else:
        size = len(delta.serialize_report(compare(paths, workspace)))
        monkeypatch.setattr(delta, 'MAX_OUTPUT_BYTES', size - 1)
        reason = 'output cap'
    out = tmp_path / 'reports' / 'delta.json'
    out.parent.mkdir()
    before = tree_state(tmp_path)
    code, captured = cli(paths, workspace, out, capsys)
    assert code == 2 and reason in json.loads(captured.err)['error']
    assert not out.exists() and tree_state(tmp_path) == before
    if cap == 'output':
        monkeypatch.setattr(delta, 'MAX_OUTPUT_BYTES', size)
        code, captured = cli(paths, workspace, out, capsys)
        assert code == 0 and len(out.read_bytes()) == size          # exactly at the cap: written


