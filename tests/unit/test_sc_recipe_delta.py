def test_a2_morro_bay_through_existing_validator_with_staged_metadata(tmp_path, workspace):
    committed = ROOT / 'regions/morro-bay/coast.json'
    left_meta = stage_repository_metadata(tmp_path / 'left-meta')
    right_meta = stage_repository_metadata(tmp_path / 'right-meta')
    catalog = json.loads((right_meta / 'catalog/sources.json').read_text())
    index = [r['id'] for r in catalog['sources']].index('noaa-bag')
    assert catalog['sources'][index]['review_status'] == 'approved'
    catalog['sources'][index]['review_status'] = 'candidate'
    (right_meta / 'catalog/sources.json').write_text(json.dumps(catalog, indent=1))
    right_recipe = tmp_path / 'right-coast.json'
    document = json.loads(committed.read_text())
    document['source_review_status']['noaa-bag'] = 'candidate'
    right_recipe.write_text(json.dumps(document, indent=2))
    # Both sides independently valid through the actual existing validator.
    for path, meta in ((committed, left_meta), (right_recipe, right_meta)):
        assert recipe.validate_recipe(recipe.read_json(path), workspace_root=workspace,
                                      metadata_root=meta)['valid']
    report = delta.compare_recipes(committed, right_recipe, left_meta, right_meta, workspace)
    assert report['changes'] == [
        row(f'/metadata/catalog~1sources.json/sources/{index}/review_status', 'approved', 'candidate'),
        row('/recipe/source_review_status/noaa-bag', 'approved', 'candidate'),
    ]
    # Every metadata file read is listed, and the list equals the allowlist exactly.
    for side, meta in (('left', left_meta), ('right', right_meta)):
        assert set(report[side]['metadata_sha256']) == READ_SET
        assert report[side]['metadata_sha256'] == {n: sha(meta / n) for n in sorted(READ_SET)}
    assert report['left']['recipe_sha256'] == SOURCE_PINS['regions/morro-bay/coast.json']
    assert report['left']['metadata_sha256']['catalog/sources.json'] == sha(ROOT / 'catalog/sources.json')
    assert report['left']['metadata_sha256'][SCHEMA] == SOURCE_PINS[SCHEMA]
    assert not list(workspace.iterdir())


