def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def tree_state(root):
    """Every entry under root (symlinks not followed) -> content hash / kind."""
    state = {}
    for folder, dirs, files in os.walk(root):
        for name in dirs + files:
            path = Path(folder) / name
            relative = path.relative_to(root).as_posix()
            if path.is_symlink():
                state[relative] = 'link:' + os.readlink(path)
            elif path.is_dir():
                state[relative] = 'dir'
            elif path.is_file():
                state[relative] = sha(path)
            else:
                state[relative] = 'special'
    return state


