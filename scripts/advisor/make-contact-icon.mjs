#!/usr/bin/env node
// Writes server/advisor/pages/icon.ts: dist/app-icon-192.png as a base64
// string for the contact card's PHOTO line (GET /contact.vcf, TA-C6). A
// committed string, not a bundler asset import, so the Worker bundle and the
// Node tests (which run server/ by type stripping) read the same bytes and
// `pnpm build` stays deterministic. tests/test_advisor_contact_card.mjs fails
// when the icon changes and this was not re-run.
//
//   node scripts/advisor/make-contact-icon.mjs           write the module
//   node scripts/advisor/make-contact-icon.mjs --check   exit 1 if it is stale
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const SOURCE = 'dist/app-icon-192.png';
export const TARGET = 'server/advisor/pages/icon.ts';

export function iconModule(png) {
  const b64 = Buffer.from(png).toString('base64');
  const lines = b64.match(/.{1,100}/g).map(line => `  '${line}'`).join(',\n');
  return `// Generated by scripts/advisor/make-contact-icon.mjs from ${SOURCE}. Do not edit.\n`
    + '// The contact card\'s PHOTO (server/advisor/pages/contact-card.ts).\n'
    + `export const CONTACT_ICON_PNG_BASE64 = [\n${lines},\n].join('');\n`;
}

const expected = iconModule(readFileSync(ROOT + SOURCE));
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(ROOT + TARGET, 'utf8'); } catch { current = ''; }
  if (current !== expected) { console.error(`${TARGET} is stale: run node scripts/advisor/make-contact-icon.mjs`); process.exit(1); }
  console.log(`${TARGET} matches ${SOURCE}.`);
} else {
  writeFileSync(ROOT + TARGET, expected);
  console.log(`Wrote ${TARGET} from ${SOURCE}.`);
}
